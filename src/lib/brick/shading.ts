// 접촉 그늘(AO)의 **모양을 정하는 상수들** — 한 파일에 모아 둔다.
//
// ★★ **왜 한 파일인가**: 이 값들은 **반드시 함께** 맞춰야 한다. 한쪽만 바꾸면 그늘이 무너진다.
//   예전엔 `world.ts`(세기)와 `BrickInstances.tsx`(곡선)에 나뉘어 있어서, 세기만 만지다가
//   **포화**(막힌 칸 2·3·4개가 전부 같은 값)를 못 보고 지나쳤다. 색 상수를 두 군데 적어 뒀다가
//   "고쳐도 화면이 안 바뀌던" 것과 같은 계열의 사고다.
//
// ★ 여기 값은 **순수 계산**이라 테스트가 가능하다 — 실제 화면 밝기와 **거리에 따른 감쇠**까지 잠근다.

/** 꼭짓점에 닿는 바깥 칸 수의 기준. 평평한 면의 꼭짓점은 항상 이만큼 막혀 있다 */
export const FLAT_BLOCKED = 3;
/** 꼭짓점에 닿는 바깥 칸의 최대 수 */
export const OUTSIDE_BLOCKED = 7;

/**
 * 첫 접촉에서 떨어지는 양 — **접촉면의 진하기**를 정한다.
 *
 * ⚠️ 크다고 그늘이 넓어지는 게 아니다. **넓이는 `SHADE_CURVE`가 정한다.**
 *   이 값은 "닿는 자리가 얼마나 어두운가"만 정한다.
 */
export const AO_FIRST = 0.60;
/** 더 깊이 막힐수록 추가로 떨어지는 양. 0이면 깊은 구석이 전부 같은 값이 된다(= 납작한 얼룩) */
export const AO_EXTRA = 0.19;
/** 하한 — **가장 깊은 구석보다 낮게.** 여기 닿으면 다시 포화한다 */
export const AO_MIN = 0.05;

/**
 * ★★★ **그늘이 얼마나 좁게 붙는가.** 이번 문제의 핵심 손잡이다.
 *
 * 🔴 사용자 신고(2026-08-04): *"바닥에 조그만 이미지 깔고 blur 많이 준 느낌. 닿는 면에
 *    그림자가 확실히 져야 하는데 지금은 blur다."* — 정확한 진단이었다.
 *
 *    밝기 값은 **지형 타일의 네 귀퉁이에만** 있고(타일이 2×2칸 = **1m**), 그 사이는 GPU가
 *    **직선으로** 채운다. 그래서 브릭이 한 귀퉁이를 어둡게 하면 그 어둠이 **1m에 걸쳐 고르게**
 *    옅어진다 — 이게 곧 블러다.
 *
 *    → 값 자체를 촘촘히 만들려면 구조를 바꿔야 하지만(칸 단위 조명), **부족분에 지수를 씌우면**
 *      같은 데이터로도 어둠을 **접촉면 쪽으로 몰아붙일 수 있다.** 지수를 키운 만큼 접촉이 밝아지므로
 *      `AO_FIRST`를 함께 키워 진하기를 유지한다. 둘은 이래서 한 쌍이다.
 *
 *    실측 프로파일(브릭이 닿은 지점에서 바깥으로, 지형 타일 1m 기준):
 *
 *      거리      0cm    25cm   50cm   75cm   100cm
 *      1.6        0.57   0.72   0.86   0.95   1.00   ← 곡선이 약해 1m 내내 고르게 번진다
 *      3.8        0.55   0.85   0.97   1.00   1.00   ← **너무 조였다.** 25cm면 화면에서 몇 픽셀이라
 *                                                      사용자에게 "그림자가 거의 없다"로 보였다
 *      1.95(지금) 0.63   0.79   0.91   0.97   1.00   ← 마인크래프트와 같은 폭(블록 한 칸)에
 *                                                      접촉면 쪽으로 쏠린 곡선
 *
 * ★ **폭 자체는 마인크래프트도 블록 한 칸(1m)이다.** 참고 이미지로 확인했다 — 좁히는 게 답이 아니라,
 *   같은 폭 안에서 **접촉면 쪽으로 쏠리게** 하는 것이 답이다. 한때 3.8까지 조였다가 되돌렸다.
 */
export const SHADE_CURVE = 1.95;

/**
 * **세로면에서 그늘을 얼마나 덜어낼지** (0 = 안 덜어냄, 1 = 세로면엔 그늘 없음).
 *
 * 꼭짓점 그늘은 주변 여덟 칸을 세는데, 거기엔 **같은 평면에 나란히 붙은 이웃 브릭**도 들어간다.
 * 평평한 벽 밑동이 `바닥 4칸 + 옆 브릭 1칸`으로 세어져 실제보다 한 단계 더 어두워진다 —
 * **옆 브릭은 벽면을 가리지 않는데도** 그렇다(면을 구분하지 않는 계산의 구조적 과대평가).
 * 윗면·밑면은 그대로 두고 세로면에서만 덜어 그 몫을 상쇄한다.
 */
export const AO_WALL_RELIEF = 0.30;

/**
 * 꼭짓점 그늘 — 막힌 칸 수 → 밝기 배율(0~1). **곡선을 먹기 전의 원값**이다.
 *
 * 평평한 면·볼록 모서리는 그대로 1.0이고 오목한 자리만 어두워진다 → **밝아지는 곳은 없다.**
 */
export function cornerAO(blocked: number): number {
  return aoFromOver(blocked - FLAT_BLOCKED);
}

/**
 * 기준(`FLAT`)보다 **몇 칸 더** 막혔는가 → 밝기 배율.
 *
 * ★ 왜 `over`를 직접 받는 갈래를 두나: 세는 방식이 두 가지다.
 *   - **브릭 기준**: 자기 몸을 빼고 바깥 7칸을 센다 → 평평한 면의 기준이 3
 *   - **세계 좌표 기준**: 주인이 없으니 8칸을 다 센다 → 평평한 면의 기준이 4
 *   기준만 다르고 **`over`는 똑같이 나온다.** 그래서 `over`로 통일해 두면 두 방식이 같은 값을 낸다
 *   (칸 단위 조명으로 넘어갈 때 이 동일성이 안전장치가 된다 — 테스트가 잠근다).
 */
export function aoFromOver(over: number): number {
  if (over <= 0) return 1;
  const deeper = (over - 1) / (OUTSIDE_BLOCKED - FLAT_BLOCKED - 1); // 0 = 첫 접촉, 1 = 완전히 막힘
  const ao = 1 - (AO_FIRST + AO_EXTRA * deeper);
  return ao < AO_MIN ? AO_MIN : ao;
}

/** 세계 좌표 기준 꼭짓점 — 여덟 칸을 다 세므로 평평한 면의 기준이 하나 더 크다 */
export const FLAT_BLOCKED_WORLD = FLAT_BLOCKED + 1;

/**
 * 원값 → **화면에 나오는 밝기**. 셰이더가 프래그먼트마다 하는 계산과 같은 식이다.
 *
 * ⚠️ 셰이더(`BrickInstances`의 `bakedLight`)와 **같은 식**이어야 테스트가 의미를 갖는다.
 *   식을 고치면 양쪽을 같이 고칠 것.
 */
export function screenShade(sky: number): number {
  const s = sky < 0 ? 0 : sky > 1 ? 1 : sky;
  return 1 - Math.pow(1 - s, SHADE_CURVE);
}
